import assert from "node:assert/strict";
import fs from "node:fs/promises";
import {activitiesForSkill, validateActivityPair, compareSkilling} from "../docs/activity-comparison.js";
import {compareCombat, combatHitChance} from "../docs/combat-comparison.js";
const catalog = JSON.parse(await fs.readFile(new URL("../docs/activity-catalog.json", import.meta.url), "utf8"));
const near = (a, b) => assert(Math.abs(a - b) < 1e-8, `${a} != ${b}`);
assert.equal(catalog.skills.length, 16);
assert.equal(new Set(catalog.activities.map(a => a.id)).size, catalog.activities.length);
assert(!JSON.stringify(catalog).includes("$expression"), "Never publish unresolved executable client expressions");
for (const skill of catalog.skills) {
  const activities = activitiesForSkill(catalog, skill.id);
  assert(activities.length >= 2, skill.name + " must offer two choices");
  assert(activities.every(a => a.skill === skill.id));
  if (skill.combat) assert(activities.every(a => catalog.foes[a.mob]?.hp > 0));
  else assert(activities.every(a => a.exp > 0 && a.duration > 0));
}
assert.throws(() => validateActivityPair(catalog, "attack", "attack/fight-mouse", "fishing/catch-shrimp"), /same skill/);
assert.throws(() => validateActivityPair(catalog, "attack", "attack/fight-mouse", "attack/fight-mouse"), /different second/);
assert.throws(() => validateActivityPair(catalog, "fishing", "missing", "also-missing"), /same skill/);
const trees = validateActivityPair(catalog, "woodcutting", "woodcutting/chop-tree", "woodcutting/chop-oak");
const base = compareSkilling({woodcutting:10}, {woodcutting:5}, trees);
near(base[0].baseSeconds, 22);
near(base[0].xpPerHour, 12 * 3600 / 22);
near(base[0].doubleChance, .14);
assert(base[0].levelMet);
assert(!base[1].levelMet, "A +5 tool bonus must not unlock level-15 oaks at trained level 10");
near(base[1].doubleChance, 0);
const doubled = compareSkilling({woodcutting:10}, {woodcutting:5}, trees, {modelDoubleUps:true, repeatSeconds:2});
near(doubled[0].cycleSeconds, 22.28);
near(doubled[0].xpPerHour, 12 * 1.14 * 3600 / 22.28);
near(compareSkilling({woodcutting:200}, {}, trees)[0].doubleChance, 1);
near(compareSkilling({woodcutting:1}, {woodcutting:-10}, trees)[0].doubleChance, 0);
assert.throws(() => compareSkilling({}, {}, trees, {prepSeconds:NaN}));
assert.throws(() => compareSkilling({}, {}, trees, {repeatSeconds:-1}));
const foes = [catalog.foes.mouse, catalog.foes.chicken];
const ranged = compareCombat({ranged:10,defense:1}, {ranged:2,attackCooldown:3}, foes, {skill:"ranged", prepSeconds:0});
near(ranged[0].hitChance, .76);
assert.equal(ranged[0].maxHit, 3);
const magic = compareCombat({evilMagic:1}, {}, foes, {skill:"evilMagic",spellMaxHit:2});
near(magic[0].hitChance, .85);
assert.equal(magic[0].maxHit, 2);
assert.throws(() => compareCombat({}, {}, foes, {skill:"evilMagic"}), /Choose a spell/);
assert.throws(() => compareCombat({}, {}, foes, {attackSeconds:0}), /attack interval/);
near(combatHitChance(1, 0, 50, "magic"), .54);
assert(catalog.foes.gurgle.special && catalog.foes["king-onyx-dragon"].special && catalog.foes.morvane.special);
console.log("Passed: same-skill pairing, unique current definitions across 16 skills, base XP timing, gear-adjusted double-up chance, trained-level gates, optional repeat model, ranged/magic formulas, missing spell handling, and special-encounter flags.");
