import assert from "node:assert/strict";
globalThis.window = {location:{hostname:"127.0.0.1",origin:"http://127.0.0.1:8065"}};
const {xpPlayerProgress,lookupXpPlayer,xpSkills} = await import("../docs/xp-player.js");
assert.equal(xpSkills.length,16);
assert.deepEqual(xpSkills.slice(0,6),["attack","strength","defense","evilMagic","ranged","piety"]);
assert.deepEqual(xpPlayerProgress({exp:{attack:6692}},"attack"),{level:7,xp:6692});
assert.deepEqual(xpPlayerProgress({exp:{strength:0}},"strength"),{level:1,xp:0},"Zero XP must fill level 1, not be treated as missing");
assert.deepEqual(xpPlayerProgress({exp:{fishing:53790.25}},"fishing"),{level:21,xp:53790.25},"Keep exact XP, including a fractional value");
assert.deepEqual(xpPlayerProgress({exp:{attack:830}},"attack"),{level:2,xp:830},"Threshold boundary must match Player Lookup");
assert.throws(()=>xpPlayerProgress({exp:{}},"attack"),/not available/);
assert.throws(()=>xpPlayerProgress({exp:{attack:-1}},"attack"),/invalid XP/);
assert.throws(()=>xpPlayerProgress({exp:{attack:"6692"}},"attack"),/invalid XP/);
assert.throws(()=>xpPlayerProgress({exp:{attack:Infinity}},"attack"),/invalid XP/);
assert.throws(()=>xpPlayerProgress({exp:{attack:150000000}},"attack"),/supported level range/);
const snapshot = {checkedAt:Date.now(),player:{name:"User12345",exp:{attack:6692,strength:0}}};
let received;
const fetcher = async (url,options) => {received={url,options};return Response.json(snapshot);};
assert.deepEqual(await lookupXpPlayer(" User12345 ",{fetcher}),snapshot);
assert.equal(received.url.href,"http://127.0.0.1:8065/api/player.json?username=User12345");
assert.equal(received.options.credentials,"omit");
assert.equal(received.options.cache,"no-store");
await assert.rejects(lookupXpPlayer("../bad",{fetcher}),/full username/);
await assert.rejects(lookupXpPlayer("Unknown",{fetcher:async()=>Response.json({error:"Player not found"},{status:404})}),/Player not found/);
await assert.rejects(lookupXpPlayer("User12345",{fetcher:async()=>new Response("<html>error</html>")}),/did not respond correctly/);
await assert.rejects(lookupXpPlayer("User12345",{fetcher:async()=>Response.json({checkedAt:Date.now(),player:{name:"User12345",exp:[]}})}),/incomplete/);
const controller = new AbortController();
controller.abort();
await lookupXpPlayer("User12345",{fetcher,signal:controller.signal});
assert(received.options.signal.aborted,"Navigation or changing the name must be able to cancel a pending lookup");
window.location = {hostname:"microscapewiki.com",origin:"https://microscapewiki.com"};
await lookupXpPlayer("User12345",{fetcher});
assert.equal(received.url.href,"https://microscape-wiki-api.pages.dev/player.json?username=User12345");
console.log("Passed: 16 skills in game order, exact XP and level thresholds, zero/missing/invalid XP, unsupported levels, public endpoint routing, safe requests, malformed profiles, upstream errors and cancellation signals.");
