import assert from "node:assert/strict";
import fs from "node:fs/promises";
import {changeLoadout,loadoutRequirements,slotAccepts,loadoutSkill,modelLoadout} from "../docs/loadout-comparison.js";
const catalog=JSON.parse(await fs.readFile(new URL("../docs/activity-catalog.json",import.meta.url),"utf8"));
const reference=JSON.parse(await fs.readFile(new URL("../docs/loadout-reference.json",import.meta.url),"utf8"));
const levels=Object.fromEntries(catalog.skills.map(s=>[s.id,50]));
const baseline={skin:"skin1",hair:"shortBrown",weapon:"bronzeScimitar",shield:"bronzeSqShield",body:"bronzeArmor"};
const original=JSON.stringify(baseline);
const improved=changeLoadout(baseline,"weapon","steelScimitar",catalog.items);
assert.equal(JSON.stringify(baseline),original,"A test loadout must not mutate the profile");
assert.equal(improved.skin,"skin1");assert.equal(improved.hair,"shortBrown");
assert.equal(slotAccepts("potion2",catalog.items.attackPotion),true);
assert.equal(slotAccepts("potion3",catalog.items.attackPotion),true);
assert.equal(slotAccepts("head",catalog.items.attackPotion),false);
assert.throws(()=>changeLoadout(baseline,"body","steelScimitar",catalog.items));
assert.throws(()=>changeLoadout(baseline,"skin","skin2",catalog.items));
const bow=changeLoadout(baseline,"weapon","shortbow",catalog.items);
assert(!bow.shield,"Two-handed weapons must release the shield");
const shield=changeLoadout(bow,"shield","pyreshellShield",catalog.items);
assert(!shield.weapon,"Selecting a shield must release a two-handed weapon");
assert.equal(changeLoadout(baseline,"weapon","",catalog.items).weapon,undefined);
assert(loadoutRequirements({weapon:"steelScimitar"},{attack:1},catalog.items).some(s=>s.includes("Attack 20")));
assert.equal(loadoutRequirements(improved,levels,catalog.items).length,0);
assert(loadoutRequirements({...bow,shield:"bronzeSqShield"},levels,catalog.items).some(s=>s.includes("two-handed")));
assert.equal(loadoutSkill(bow,catalog.items),"ranged");
assert.equal(loadoutSkill({weapon:"staff"},catalog.items),"evilMagic");
assert.equal(loadoutSkill({weapon:"staff"},catalog.items,"attack"),"attack");
const model=equipment=>modelLoadout({equipment,levels,catalog,foe:catalog.foes.chicken});
const a=model(baseline),b=model(improved);
assert(!a.reason&&!b.reason);assert(b.row.maxHit>=a.row.maxHit);assert(b.row.xpPerHour>=a.row.xpPerHour);
assert.equal(modelLoadout({equipment:baseline,levels:{attack:1},catalog,foe:catalog.foes.mouse}).issues.length,0);
assert.equal(modelLoadout({equipment:improved,levels:{attack:1},catalog,foe:catalog.foes.mouse}).row,null,"Unusable equipment must not receive a usable combat rate");
assert(modelLoadout({equipment:bow,levels,catalog,foe:catalog.foes.mouse}).issues.some(s=>s.includes("arrows")));
const ranged=modelLoadout({equipment:{...bow,ammo:"arrows"},levels,catalog,foe:catalog.foes.mouse});
assert.equal(ranged.reason,null);assert.equal(ranged.row.xpRateStatus,"unverified");
const magic=modelLoadout({equipment:{weapon:"staff"},levels,catalog,foe:catalog.foes.mouse,spellId:"windStrike"});
assert.equal(magic.reason,null);assert.equal(magic.row.maxHit,2);assert(magic.notes.some(s=>s.includes("rune")));
assert(modelLoadout({equipment:{weapon:"staff"},levels,catalog,foe:catalog.foes.mouse}).issues.some(s=>s.includes("spell")));
assert(modelLoadout({equipment:baseline,levels,catalog,foe:catalog.foes.gurgle}).reason.includes("special"));
assert(modelLoadout({equipment:baseline,levels,catalog,foe:catalog.foes["crocodile-safe"]}).reason.includes("safe spot"));
assert.throws(()=>modelLoadout({equipment:baseline,levels,catalog,foe:catalog.foes.mouse,prepSeconds:NaN}));
assert.equal(reference.abilities.length,89);
assert(reference.abilities.some(a=>a.onItem==="pyreshellShield"&&a.wikiId==="pyreshell-ward"));
assert(reference.abilities.every(a=>catalog.items[a.onItem]));
console.log("Passed: immutable profile baseline, slot filtering, potion slots, two-handed swaps, trained-level gates, weapon style detection, combat deltas, missing arrows/spells, special encounters, unverified XP labels and 89 equipment-granted abilities.");
